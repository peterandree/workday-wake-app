def apply(page, pairs, extra=()):
    p = os.path.join(D, page)
    html = open(p, encoding="utf-8").read()
    miss = 0
    for old, new in pairs:
        if old not in html:
            print("MISS %s/%s: %r" % (D, page, old[:70]))
            miss += 1
        html = html.replace(old, new)
    for old, new in extra:
        html = html.replace(old, new)
    open(p, "w", encoding="utf-8", newline="").write(html)
    print("de/%s done (%d misses)" % (page, miss))

